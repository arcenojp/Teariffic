-- Row Level Security
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.inventory enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy "Users can read own profile; staff can read all"
on public.profiles for select to authenticated
using (id = (select auth.uid()) or public.is_staff());

create policy "Admins can update profiles"
on public.profiles for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Categories are readable by everyone"
on public.categories for select to anon, authenticated using (true);
create policy "Admins manage categories"
on public.categories for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Active products are public; staff can read all"
on public.products for select to anon, authenticated
using (active = true or public.is_staff());
create policy "Admins manage products"
on public.products for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Staff can read inventory"
on public.inventory for select to authenticated using (public.is_staff());
create policy "Admins manage inventory"
on public.inventory for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Customers read own orders; staff read all"
on public.orders for select to authenticated
using (customer_id = (select auth.uid()) or public.is_staff());
create policy "Signed in users create own orders"
on public.orders for insert to authenticated
with check (customer_id = (select auth.uid()));
create policy "Staff update orders"
on public.orders for update to authenticated
using (public.is_staff()) with check (public.is_staff());
create policy "Admins delete orders"
on public.orders for delete to authenticated
using (public.is_admin());

-- A user may remove their own still-pending order (used to clean up if item
-- insertion fails during this demo's two-step browser checkout).
create policy "Owners delete own pending orders"
on public.orders for delete to authenticated
using (customer_id = (select auth.uid()) and status = 'pending');

create policy "Order owner or staff can read order items"
on public.order_items for select to authenticated
using (exists (select 1 from public.orders o where o.id=order_id and (o.customer_id=(select auth.uid()) or public.is_staff())));
create policy "Users can add items to own order"
on public.order_items for insert to authenticated
with check (exists (select 1 from public.orders o where o.id=order_id and o.customer_id=(select auth.uid())));
create policy "Staff can add POS items"
on public.order_items for insert to authenticated
with check (public.is_staff());
create policy "Admins can delete order items"
on public.order_items for delete to authenticated
using (public.is_admin());

grant usage on schema public to anon, authenticated;
grant select on public.categories, public.products to anon, authenticated;
grant select, insert, update, delete on public.profiles, public.categories, public.products, public.inventory, public.orders, public.order_items to authenticated;
grant usage, select on all sequences in schema public to authenticated;

