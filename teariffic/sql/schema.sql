-- Teariffic database schema for Supabase PostgreSQL
-- Run the complete file in Supabase Dashboard > SQL Editor > New query.

create extension if not exists pgcrypto;

create type public.app_role as enum ('customer', 'cashier', 'admin');
create type public.order_status as enum ('pending', 'preparing', 'ready', 'completed', 'cancelled');
create type public.order_type as enum ('pickup', 'dine_in');
create type public.payment_method as enum ('cash', 'gcash');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role public.app_role not null default 'customer',
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''), 'customer')
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role in ('admin','cashier')
  );
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table public.products (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  name text not null,
  description text not null default '',
  price numeric(10,2) not null check (price > 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.inventory (
  id bigint generated by default as identity primary key,
  ingredient text not null unique,
  quantity numeric(10,2) not null default 0 check (quantity >= 0),
  unit text not null default 'pcs',
  low_stock_level numeric(10,2) not null default 5 check (low_stock_level >= 0),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default (
    'TRF-' || to_char(now() at time zone 'utc', 'YYMMDD') || '-' ||
    upper(substr(encode(gen_random_bytes(5), 'hex'), 1, 8))
  ),
  customer_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  order_type public.order_type not null default 'pickup',
  status public.order_status not null default 'pending',
  payment_method public.payment_method not null default 'cash',
  subtotal numeric(10,2) not null check (subtotal >= 0),
  total numeric(10,2) not null check (total >= 0),
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  size text not null check (size in ('Regular','Large')),
  sugar_level text not null check (sugar_level in ('0%','25%','50%','75%','100%')),
  ice_level text not null check (ice_level in ('No ice','Less ice','Regular')),
  toppings text not null default '',
  quantity integer not null check (quantity between 1 and 99),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  line_total numeric(10,2) not null check (line_total >= 0)
);

create index orders_customer_created_idx on public.orders(customer_id, created_at desc);
create index orders_created_idx on public.orders(created_at desc);
create index order_items_order_idx on public.order_items(order_id);

